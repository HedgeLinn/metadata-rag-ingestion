HEADERS = ["问题", "正确回答", "必答点", "选答点", "参考文件"]


def generate_docs() -> Path:
    doc_dir = ROOT / "datasets" / "demo"
    doc_dir.mkdir(parents=True, exist_ok=True)
    for name, content in DEMO_DOCS.items():
        (doc_dir / f"{name}.md").write_text(content, encoding="utf-8")
        print(f"[doc] {name}.md ({len(content)} 字)")
    return doc_dir


def generate_testset() -> Path:
    out = ROOT / "examples" / "demo_testset.xlsx"
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "测试集"
    ws.append(HEADERS)
    for row in DEMO_TESTSET:
        ws.append(list(row))
    wb.save(out)
    print(f"[testset] {out} ({len(DEMO_TESTSET)} 题)")
    return out


